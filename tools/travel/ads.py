"""광고성 카드사 이벤트 거르기 — Mr. Cards `paymorevent/lib/ad-events.ts`의 isAd와 같은 규칙(바꾸면 둘 다 고치세요).

보험 가입·조회·상담, 대출·리볼빙·분할납부·투자·연금 같은 금융상품, 통신·인터넷·멤버십·구독 가입,
여행사 패키지(하나투어·모두투어 …)·해외직구 쿠폰(알리익스프레스·테무)·가전·교육 제휴, 홍보·정보성 글은
Mr. Cards에서 안 보이므로(상세 링크도 없음) Mr. Travel 혜택·여행준비에서도 뺍니다.
"""
import re

AD_RX = re.compile("|".join([
    r"(?:자동차|운전자|여행자?|해외\s*여행|장기\s*체류|일본\s*여행|면역\s*질환|홀인원|제휴|다이렉트|펫|실손)\s*보험",
    r"보험\s*(?:가입|상담|진단|보장|료\s*(?:확인|조회))|내\s*보험|손해\s*보험|손보|삼성화재|현대해상|DB손|캐롯|생명\s*제휴|헬스케어\s*\(암\)",
    r"대출|카드론|현금\s*서비스|리볼빙|일부\s*결제|분할\s*납부|나눠\s*낼|발행\s*어음|증권|투자|연금|노란\s*우산|적금|예금|펀드|대신\s*청구|특별\s*금리|바우처\s*신청|부부\s*통장",
    r"오토\s*(?:카드\s*)?할부|장기\s*할부|신차타GO|인증\s*중고차|월\s*[\d,]+원으로",
    r"상담|견적|멤버십\s*신규\s*가입|가입\s*(?:하면|하고|하시고)|신규\s*가입|가입자\s*한정|개통|인터넷\s*[·+&,]?\s*TV|정수기|상조|삼성\s*AI\s*구독|AI\s*구독\s*삼성|구독\s*(?:하고|할인)|구독삼성|공식\s*인증\s*대리점|이사하고",
    r"하나투어|모두투어|노랑풍선|참좋은\s*여행|교원\s*투어|인터파크\s*투어|롯데관광|한진\s*트래블|알리\s*익스프레스|aliexpress|테무|temu|LG\s*전자|삼성\s*전자|가전\s*(?:캐시백|구매)|토익|YBM",
    r"제휴\s*상품|MD\s*추천|라방|핫딜|나눔|띵크어스|신년\s*운세|마케팅\s*정보|수신.{0,3}동의|로카\s*파트너스|받을\s*수\s*있는지|결혼\s*도움방",
]), re.I)
BILL_RX = re.compile(r"자동\s*납부|자동\s*이체|무료\s*\S*보험")


def is_ad(title: str) -> bool:
    t = title or ""
    return bool(AD_RX.search(t)) and not BILL_RX.search(t)
