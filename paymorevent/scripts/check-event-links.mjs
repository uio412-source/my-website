import './ensure-card-data.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {offerApplies,linkedOffers} from '../lib/catalog-model.ts';
import {mergeEventRefresh} from '../lib/event-refresh.ts';
import {eventSourceKey} from '../lib/event-identity.ts';
import {eventSchema} from '../lib/catalog-validation.ts';
const cards=JSON.parse(fs.readFileSync('data/cards.json','utf8'));
const updates=JSON.parse(fs.readFileSync('data/event-link-updates.json','utf8')).events;
const travelers=cards.filter(c=>c.familyId==='family-kb-09563');assert.equal(travelers.length,3);
for(const o of updates){assert(eventSchema.safeParse(o).success,JSON.stringify(eventSchema.safeParse(o).error));}
const rakuten=updates.find(o=>o.sourceUrl.includes('1001534'));
for(const c of travelers)assert(offerApplies(c,rakuten),'All reviewed family designs must match');
assert(!offerApplies({...travelers[0],brands:['국내전용']},rakuten),'Domestic-only must fail the brand constraint');
assert(!offerApplies({...travelers[0],brands:['Visa']},rakuten),'Visa must not inherit Mastercard event');
assert(!offerApplies({...travelers[0],brands:['Visa']},{...rakuten,cardIds:[travelers[0].id]}),'IDs cannot bypass constraints');
assert(offerApplies({...travelers[0],brands:['MASTER']},rakuten));
assert(!offerApplies({...travelers[0],issuer:'신한카드',issuerGroup:'신한'},rakuten),'Issuer must match');
const webtour=updates.find(o=>o.sourceUrl.includes('1002226'));
assert(offerApplies(travelers[0],webtour));assert(!offerApplies({...travelers[0],type:'credit'},webtour));
assert(!offerApplies({...travelers[0],name:'KB BC 체크카드'},webtour));
const other=cards.find(c=>c.issuer===travelers[0].issuer&&c.type==='debit'&&c.familyId!==travelers[0].familyId);
assert(!offerApplies(other,rakuten));assert(offerApplies(other,webtour));
const next={...rakuten,verificationLevel:'official_list',cardIds:[],cardNames:[],cardTarget:undefined,verifiedAt:'2026-10-18'};
const retained=mergeEventRefresh(next,rakuten);assert.equal(retained.cardTarget.scope,'family');assert.equal(retained.detailVerifiedAt,'2026-10-17');assert.equal(retained.listingVerifiedAt,'2026-10-18');
assert.equal(mergeEventRefresh({...next,endsAt:'2026-11-30'},rakuten).cardTarget,undefined,'Changed event period cannot inherit old verified terms');
assert.equal(eventSourceKey(rakuten),eventSourceKey({sourceUrl:'https://m.kbcard.com/BON/DVIEW/MBBV0004?evntId=1001534'}));
assert(!linkedOffers(travelers[0],updates).some(o=>o.status==='needs_review'));
assert(!linkedOffers(travelers[0],updates).some(o=>o.endsAt<'2026-10-17'));
const issuance=updates.find(o=>o.sourceUrl.includes('1002229'));assert.equal(issuance.usageEndsAt,'2026-11-10');assert(issuance.eligibilityLabel.includes('신규'));
console.log(JSON.stringify({status:'passed',reviewed:updates.length,active:updates.filter(o=>o.status==='active').length,pending:updates.filter(o=>o.status==='needs_review').length,familyVariants:travelers.length,negativeEligibility:true,refreshPreservation:true,periodRollover:true,mobileIdentity:true}));
