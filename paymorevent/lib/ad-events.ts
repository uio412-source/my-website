// 광고성 이벤트 거르기 — Mr. Cards 어디에도(카드사 이벤트·내 카드 이벤트·카드 상세·비교) 보여 주지 않음.
// 카드를 써서 받는 혜택이 아니라 제휴사 상품 가입·조회·상담이나 정보성 안내를 권하는 것들입니다.
// 첫 화면에서 이벤트를 받자마자 거르므로(pages/main.tsx) 작은 파일로 둡니다. 수집 규칙도 같은 기준(docs/data-update.md 3장).
const AD_RX = new RegExp([
  // 보험: 가입·보험료 조회·보장분석 상담 (이미 내는 보험료를 카드로 자동납부·자동이체하는 건 아래 BILL_RX로 남김)
  String.raw`(?:자동차|운전자|여행자?|해외\s*여행|장기\s*체류|일본\s*여행|면역\s*질환|홀인원|제휴|다이렉트|펫|실손)\s*보험`,
  String.raw`보험\s*(?:가입|상담|진단|보장|료\s*(?:확인|조회))|내\s*보험|손해\s*보험|손보|삼성화재|현대해상|DB손|캐롯|생명\s*제휴|헬스케어\s*\(암\)`,
  // 대출·할부 금융·투자 같은 금융상품
  String.raw`대출|카드론|현금\s*서비스|리볼빙|일부\s*결제|분할\s*납부|나눠\s*낼|발행\s*어음|증권|투자|연금|노란\s*우산|적금|예금|펀드|대신\s*청구|특별\s*금리|바우처\s*신청|부부\s*통장`,
  String.raw`오토\s*(?:카드\s*)?할부|장기\s*할부|신차타GO|인증\s*중고차|월\s*[\d,]+원으로`,
  // 가입·상담·견적 유도, 통신·인터넷·멤버십·구독 가입, 휴대폰 개통·대리점
  String.raw`상담|견적|멤버십\s*신규\s*가입|가입\s*(?:하면|하고|하시고)|신규\s*가입|가입자\s*한정|개통|인터넷\s*[·+&,]?\s*TV|정수기|상조|삼성\s*AI\s*구독|AI\s*구독\s*삼성|구독\s*(?:하고|할인)|구독삼성|공식\s*인증\s*대리점|이사하고`,
  // 여행사 패키지·해외직구 플랫폼·가전·교육 제휴 광고
  String.raw`하나투어|모두투어|노랑풍선|참좋은\s*여행|교원\s*투어|인터파크\s*투어|롯데관광|한진\s*트래블|알리\s*익스프레스|aliexpress|테무|temu|LG\s*전자|삼성\s*전자|가전\s*(?:캐시백|구매)|토익|YBM`,
  // 혜택이 아닌 홍보·정보성: 제휴 상품 소개·MD 추천·라이브커머스·기부·운세·마케팅 수신 동의·포인트 조회 유도
  String.raw`제휴\s*상품|MD\s*추천|라방|핫딜|나눔|띵크어스|신년\s*운세|마케팅\s*정보|수신.{0,3}동의|로카\s*파트너스|받을\s*수\s*있는지|결혼\s*도움방`,
].join('|'), 'i');
// 예외: 이미 내는 보험료·요금 자동납부·자동이체, 카드 자체 서비스인 무료 보험(플래티넘 무료 여행자보험 등)
const BILL_RX = /자동\s*납부|자동\s*이체|무료\s*\S*보험/;

/** 제목으로 본 광고성 이벤트인지 */
export const isAd = (title: string) => AD_RX.test(title) && !BILL_RX.test(title);

/** 새로 발급·처음 쓰는 회원 대상 홍보(연회비 캐시백·면제, 출시 기념, '한번 써보세요', 카드 신청하고 …). 이미 가진 카드에는 해당 안 됨 */
export const isIssuePromo = (title: string) =>
  /연회비\s*(?:\d+%\s*)?(?:캐시백|면제|상당|환급)|한번\s*써\s*보세요|출시\s*기념|카드\s*출시|발급\s*(?:시|하고|하면)|신규\s*회원|웰컴\s*회원|카드\s*받고|카드\s*신청하고/.test(title);
